#!/usr/bin/env bash
# Blue-green deploy of one version: deploy.sh <version>
# pull images → shared stack up → migrations (once) → start the idle colour → wait until ready →
# switch the proxy (caddy reload) → drain → stop the old colour → wait until the new one leads background work.
# A failure before the switch leaves the active colour untouched. See docs/10-deployment.md.
set -euo pipefail
# shellcheck source=deploy/lib.sh
. "$(dirname "$0")/lib.sh"

# Internal: rollback.sh calls `deploy.sh --rollback <steps> <version>`.
MODE=deploy; STEPS=0
if [ "${1:-}" = --rollback ]; then MODE=rollback; STEPS=${2:?}; shift 2; fi
VERSION=${1:-}
[ -n "$VERSION" ] || die "usage: deploy.sh <version>"
valid_version "$VERSION" || die "invalid version '$VERSION' (allowed: $VERSION_RE)"
[ -f "$APP_ENV_FILE" ] || die "missing $APP_ENV_FILE (the API's environment, see .env.example)"

lock
read_state
if [ "$MODE" = rollback ]; then
  # Re-checked under the lock: the history may have changed since rollback.sh read it.
  [ "${HISTORY[$STEPS]:-}" = "$VERSION" ] || die "history changed, rollback aborted (now: ${HISTORY[*]:-empty})"
fi
OLD=$ACTIVE_COLOR
TARGET=$(other "${OLD:-green}")   # first deploy goes to blue
OLD_VERSION=${HISTORY[0]:-}
log "$MODE $VERSION → $TARGET (active: ${OLD:-none}${OLD_VERSION:+ $OLD_VERSION})"
record "start $MODE version=$VERSION target=$TARGET active=${OLD:-none}"
fail() { record "failed $MODE version=$VERSION target=$TARGET: $*"; die "$*"; }

# 1. Images
if [ "$PULL" = 1 ]; then
  docker pull -q "$API_IMAGE:$VERSION" >/dev/null || fail "cannot pull $API_IMAGE:$VERSION"
  docker pull -q "$WEB_IMAGE:$VERSION" >/dev/null || fail "cannot pull $WEB_IMAGE:$VERSION"
else
  docker image inspect "$API_IMAGE:$VERSION" "$WEB_IMAGE:$VERSION" >/dev/null 2>&1 || fail "images $VERSION not present locally (PULL=0)"
fi
log "images: $(docker image inspect -f '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$API_IMAGE:$VERSION") (git sha)"

# 2. Shared stack (idempotent). Before the first switch the proxy points at the target colour.
write_upstream() { # <colour> <version>
  local tmp="$UPSTREAM.tmp"
  # /api/*: a request from a proxy on this host (e.g. 1Panel's OpenResty in front of Caddy, itself behind a
  # CDN) carries the visitor's address in X-Real-IP; pass it on as the last X-Forwarded-For entry, which the
  # API reads for the captcha rate limit and the audit log (lib/client-ip.ts). Anyone else can't set it.
  cat >"$tmp" <<EOF
# generated by deploy.sh $(ts): active colour $1 ($2)
handle /api/* {
	@via_local_proxy {
		remote_ip 127.0.0.1/32 ::1/128
		header X-Real-IP *
	}
	reverse_proxy @via_local_proxy 127.0.0.1:$(port "$1" API) {
		header_up X-Forwarded-For {http.request.header.X-Real-IP}
	}
	reverse_proxy 127.0.0.1:$(port "$1" API)
}
handle /scrcpy-relay* {
	reverse_proxy 127.0.0.1:$(port "$1" RELAY)
}
handle {
	reverse_proxy 127.0.0.1:$(port "$1" WEB)
}
EOF
  mv -f "$tmp" "$UPSTREAM"
}
[ -f "$UPSTREAM" ] || write_upstream "$TARGET" "$VERSION"
dc_shared up -d --wait postgres redis >/dev/null || fail "postgres/redis did not become healthy"
dc_shared up -d proxy >/dev/null || fail "proxy did not start"

# 3. Migrations: once per deploy, before the new code runs (they must stay backward compatible: the old
#    colour keeps serving on the new schema until the switch, and a rollback runs old code on it).
log "migrations"
dc_app "$TARGET" "$VERSION" run --rm --no-deps -T api node dist/db/migrate.js 2>&1 | sed 's/^/  migrate: /' \
  || fail "migrations failed"
if [ "$SEED_ON_DEPLOY" = 1 ]; then
  dc_app "$TARGET" "$VERSION" run --rm --no-deps -T api node dist/db/seed.js 2>&1 | sed 's/^/  seed: /' || fail "seed failed"
fi

# 4. Start the idle colour and wait until it is ready (its own version answers on its own port).
log "starting $TARGET"
dc_app "$TARGET" "$VERSION" up -d --force-recreate --remove-orphans >/dev/null 2>&1 || fail "cannot start $TARGET"
deadline=$((SECONDS + READY_TIMEOUT)); ready=""
while [ $SECONDS -lt $deadline ]; do
  body=$(ready_json "$TARGET")
  if [ "$(json_field version <<<"$body")" = "$VERSION" ] && [ "$(json_field ok <<<"$body")" = true ] \
     && http_get -o /dev/null "http://127.0.0.1:$(port "$TARGET" WEB)/" 2>/dev/null; then ready=1; break; fi
  sleep 1
done
if [ -z "$ready" ]; then
  dc_app "$TARGET" "$VERSION" logs --tail 40 api >&2 || true
  dc_app "$TARGET" "$VERSION" down >/dev/null 2>&1 || true
  fail "$TARGET did not become ready within ${READY_TIMEOUT}s (last: ${body:-no answer}); active colour unchanged"
fi
log "$TARGET ready: $body"

# 5. Switch: rewrite the upstreams and reload Caddy (graceful, atomic). Verified through the proxy.
reload_proxy() { dc_shared exec -T proxy caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile --force >/dev/null 2>&1; }
write_upstream "$TARGET" "$VERSION"
reload_proxy || { [ -n "$OLD" ] && write_upstream "$OLD" "$OLD_VERSION" && reload_proxy; dc_app "$TARGET" "$VERSION" down >/dev/null 2>&1 || true; fail "caddy reload failed; reverted"; }
if [[ ${SITE_ADDRESS:-} == :* ]]; then PROXY_URL="http://127.0.0.1${SITE_ADDRESS}"; CURL_PROXY=()
else PROXY_URL="https://${SITE_ADDRESS}"; CURL_PROXY=(--resolve "${SITE_ADDRESS}:${PROXY_HTTPS_PORT:-443}:127.0.0.1"); fi
seen=""
for _ in $(seq 1 30); do
  seen=$(http_get "${CURL_PROXY[@]}" "$PROXY_URL$READY_PATH" 2>/dev/null | json_field color || true)
  [ "$seen" = "$TARGET" ] && break
  sleep 1
done
if [ "$seen" = "$TARGET" ]; then log "switched: proxy → $TARGET ($VERSION)"
else log "WARNING: proxy check via $PROXY_URL did not confirm $TARGET (saw '${seen:-nothing}'); the upstream file points at $TARGET"; fi

# 6. State: newest first, the deployed version removed from older positions; a rollback drops the
#    versions it rolled back from (they are no rollback targets any more).
if [ "$MODE" = rollback ]; then NEW_HISTORY=("${HISTORY[@]:$STEPS}")
else NEW_HISTORY=("$VERSION"); for v in "${HISTORY[@]}"; do [ "$v" = "$VERSION" ] || NEW_HISTORY+=("$v"); done; fi
write_state "$TARGET" "${NEW_HISTORY[@]}"
record "switched $MODE version=$VERSION active=$TARGET previous=${OLD:-none}${OLD_VERSION:+/$OLD_VERSION}"

# 7. Drain, then stop the old colour gracefully (SIGTERM; it releases background work when its tasks are done).
if [ -n "$OLD" ]; then
  log "draining ${DRAIN_SECONDS}s, then stopping $OLD"
  sleep "$DRAIN_SECONDS"
  dc_app "$OLD" none down >/dev/null 2>&1 || log "WARNING: stopping $OLD reported an error"
fi
# A leftover of the target colour's previous run can't exist (force-recreated); stop the other colour if it
# runs without being the previous active one (e.g. a failed earlier deploy).
[ -z "$OLD" ] && dc_app "$(other "$TARGET")" none down >/dev/null 2>&1 || true

# 8. The new colour takes over background work once the old leader released it.
deadline=$((SECONDS + LEADER_TIMEOUT)); bg=""
while [ $SECONDS -lt $deadline ]; do
  bg=$(ready_json "$TARGET" | json_field background); [ "$bg" = leader ] && break; sleep 1
done
if [ "$bg" = leader ]; then log "$TARGET runs background work"; else log "WARNING: $TARGET background=${bg:-unknown} after ${LEADER_TIMEOUT}s"; fi

# 9. Local images that are neither recorded nor running are removed (rollback targets stay).
if [ "$PRUNE_IMAGES" = 1 ]; then
  for img in "$API_IMAGE" "$WEB_IMAGE"; do
    docker image ls --format '{{.Tag}}' "$img" | while read -r tag; do
      keep=""; for v in "${NEW_HISTORY[@]}"; do [ "$tag" = "$v" ] && keep=1; done
      [ -n "$keep" ] || docker image rm "$img:$tag" >/dev/null 2>&1 || true
    done
  done
fi

record "done $MODE version=$VERSION active=$TARGET history=${NEW_HISTORY[*]}"
echo "RESULT: $MODE ok | version $VERSION | active $TARGET | previous ${OLD:-none}${OLD_VERSION:+ ($OLD_VERSION)} | history ${NEW_HISTORY[*]} | background ${bg:-unknown}"
