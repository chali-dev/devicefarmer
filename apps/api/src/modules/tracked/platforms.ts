import { badRequest } from '../../lib/errors.js';
import { assertPlatformEnabled, isPlatformEnabled } from '../../lib/platforms-enabled.js';
import type { TrackedAccount } from '../../db/schema.js';

/**
 * Platform registry for tracked accounts (追踪账号). Adding a platform = one entry here
 * (URL/handle normalisation + optional data source).
 *
 * Data sources: an official API used with credentials the owner configured (`kind: 'api'`, YouTube), or —
 * by the owner's decision of 2026-11-18, Instagram only — reading the profile header in the platform's app
 * on the account's own 采集手机 (`kind: 'device'`, instagram-device.ts: navigation + screen reads,
 * paced, stops on any challenge). No other scraping (no web pages, no other platforms). Manual entry was
 * removed; a platform without a source has no data mode (`manual_only` = no source, legacy rows only).
 */

export interface ParsedProfile {
  platform: string;
  /** Normalised identity, unique per user + platform (lowercase handle, or a case-sensitive YouTube channel id). */
  handle: string;
  /** Canonical profile URL generated by us (never the raw input). */
  profileUrl: string;
  /** Known without an API call (YouTube /channel/UC… URLs). */
  externalId: string | null;
}

export interface ProfileData {
  externalId: string;
  displayName: string | null;
  avatarUrl: string | null;
  bio: string | null;
  followers: number | null;
  following: number | null;
  posts: number | null;
  views: number | null;
  /** Source-specific values a later call of the same refresh needs (e.g. the YouTube uploads playlist). */
  meta?: Record<string, string>;
  /** Metrics the source only knows approximately (the app abbreviated them). */
  approx?: Metric[];
  /** Verified badge, when the source shows it. */
  verified?: boolean | null;
  /** Private profile (counters may still be visible). */
  private?: boolean;
}

/** What a refresh passes to its source (task log, cancel signal). */
export interface SourceContext {
  log?: (level: 'info' | 'warn' | 'error', message: string, data?: Record<string, unknown>) => Promise<void>;
  signal?: AbortSignal;
  /** For 风控记录 rows (risk_events): the tracked account and who started the refresh. */
  trackedAccountId?: string | null;
  userId?: string | null;
}

export interface PostData {
  externalId: string;
  url: string | null;
  title: string | null;
  publishedAt: Date | null;
  views: number | null;
  likes: number | null;
  comments: number | null;
}

export type Metric = 'followers' | 'following' | 'posts' | 'views';

/** Data source of one platform: an official API, or the app on the account's 采集手机. */
export interface TrackedSource {
  /** Snapshot source written by a refresh. */
  kind: 'api' | 'device';
  capabilities: { profile: boolean; recentPosts: boolean; metrics: Metric[] };
  /**
   * Whether what it needs is configured: the YouTube API key (platform-wide); a device source is always "configured"
   * at platform level, the account's own 采集手机 is checked by requireConfigured(account).
   */
  isConfigured(): Promise<boolean>;
  /** Throws the coded "can't run" error (tracked.youtube_no_api_key; tracked.no_phone / phone_not_allowed / collector_halted). */
  requireConfigured(account?: Pick<TrackedAccount, 'userId' | 'instanceId'>): Promise<void>;
  fetchProfile(account: Pick<TrackedAccount, 'handle' | 'externalId' | 'userId' | 'instanceId'>, ctx?: SourceContext): Promise<ProfileData>;
  /** `profile` is the result of fetchProfile in the same refresh (sources may reuse what it found). */
  fetchRecentPosts(account: Pick<TrackedAccount, 'handle' | 'externalId'>, profile: ProfileData, limit: number): Promise<PostData[]>;
}

export interface PlatformDef {
  id: string;
  label: string;
  hosts: string[];
  /** Metrics shown for this platform. */
  metrics: Metric[];
  /** Path of a profile URL (already decoded, without query/hash) → identity, or null if it is not a profile. */
  fromPath(path: string): Omit<ParsedProfile, 'platform' | 'profileUrl'> | null;
  /** Bare handle input (no URL), "@" already stripped → identity, or null if invalid. */
  fromHandle(handle: string): Omit<ParsedProfile, 'platform' | 'profileUrl'> | null;
  profileUrl(p: Omit<ParsedProfile, 'platform' | 'profileUrl'>): string;
  source?: TrackedSource;
}

const YT_CHANNEL = /^UC[A-Za-z0-9_-]{22}$/;
/** YouTube handles: 3–30 letters/digits (any script), `_`, `-`, `.`. Case-insensitive. */
const YT_HANDLE = /^[\p{L}\p{N}._-]{3,30}$/u;
const IG_USER = /^[A-Za-z0-9._]{1,30}$/;
const IG_RESERVED = new Set(['p', 'reel', 'reels', 'explore', 'stories', 'accounts', 'tv', 'direct', 'about', 'developer', 'legal', 'web', 'challenge']);
const TT_USER = /^[A-Za-z0-9._]{2,24}$/;

const youtube: PlatformDef = {
  id: 'youtube',
  label: 'YouTube',
  hosts: ['youtube.com', 'www.youtube.com', 'm.youtube.com'],
  metrics: ['followers', 'posts', 'views'],
  fromPath(path) {
    const seg = path.split('/').filter(Boolean);
    if (seg[0]?.startsWith('@')) return youtube.fromHandle(seg[0].slice(1));
    if (seg[0] === 'channel' && seg[1] && YT_CHANNEL.test(seg[1])) return { handle: seg[1], externalId: seg[1] };
    return null;
  },
  fromHandle(h) {
    if (YT_CHANNEL.test(h)) return { handle: h, externalId: h };
    return YT_HANDLE.test(h) ? { handle: h.toLowerCase(), externalId: null } : null;
  },
  profileUrl: (p) => (YT_CHANNEL.test(p.handle) ? `https://www.youtube.com/channel/${p.handle}` : `https://www.youtube.com/@${encodeURIComponent(p.handle)}`),
};

const instagram: PlatformDef = {
  id: 'instagram',
  label: 'Instagram',
  hosts: ['instagram.com', 'www.instagram.com', 'm.instagram.com'],
  metrics: ['followers', 'following', 'posts'],
  fromPath(path) {
    const seg = path.split('/').filter(Boolean);
    if (seg.length !== 1 || IG_RESERVED.has(seg[0]!.toLowerCase())) return null;
    return instagram.fromHandle(seg[0]!);
  },
  fromHandle: (h) => (IG_USER.test(h) && !IG_RESERVED.has(h.toLowerCase()) ? { handle: h.toLowerCase(), externalId: null } : null),
  profileUrl: (p) => `https://www.instagram.com/${p.handle}/`,
};

const tiktok: PlatformDef = {
  id: 'tiktok',
  label: 'TikTok',
  hosts: ['tiktok.com', 'www.tiktok.com', 'm.tiktok.com'],
  metrics: ['followers', 'following', 'posts', 'views'],
  fromPath(path) {
    const seg = path.split('/').filter(Boolean);
    return seg.length === 1 && seg[0]!.startsWith('@') ? tiktok.fromHandle(seg[0]!.slice(1)) : null;
  },
  fromHandle: (h) => (TT_USER.test(h) ? { handle: h.toLowerCase(), externalId: null } : null),
  profileUrl: (p) => `https://www.tiktok.com/@${p.handle}`,
};

export const PLATFORMS: PlatformDef[] = [youtube, instagram, tiktok];
export const PLATFORM_IDS = PLATFORMS.map((p) => p.id) as [string, ...string[]];

export function platformDef(id: string): PlatformDef {
  const p = PLATFORMS.find((x) => x.id === id);
  if (!p) throw badRequest(`unsupported platform: ${id}`, 'tracked.unsupported_platform', { platform: id });
  return p;
}

/** Registers the data source of a platform (keeps the clients out of this module). */
export function registerSource(id: string, source: TrackedSource): void {
  platformDef(id).source = source;
}

/**
 * Normalises a profile URL or handle. With a URL the platform comes from the host (a given
 * `platform` must match); a bare handle (`@name`, `name`, YouTube `UC…`) needs `platform`.
 * The platform must be enabled (platform.disabled).
 */
export function parseProfile(input: string, platform?: string): ParsedProfile {
  const p = parse(input, platform);
  assertPlatformEnabled(p.platform);
  return p;
}

function parse(input: string, platform?: string): ParsedProfile {
  const raw = input.trim();
  if (!raw) throw badRequest('请输入主页链接或账号', 'tracked.input_required');
  const looksLikeUrl = /^[a-z][a-z0-9+.-]*:\/\//i.test(raw) || /^[a-z0-9.-]+\.[a-z]{2,}\//i.test(raw)
    || PLATFORMS.some((p) => p.hosts.includes(raw.toLowerCase()));
  if (looksLikeUrl) {
    let url: URL;
    try { url = new URL(/^[a-z][a-z0-9+.-]*:\/\//i.test(raw) ? raw : `https://${raw}`); } catch { throw badRequest('链接格式不正确', 'tracked.bad_profile_url'); }
    if (url.protocol !== 'https:' && url.protocol !== 'http:') throw badRequest('链接格式不正确', 'tracked.bad_profile_url');
    const host = url.hostname.toLowerCase();
    const def = PLATFORMS.find((p) => p.hosts.includes(host));
    if (!def) throw badRequest(`不支持的网站：${host}`, 'tracked.unsupported_host', { host });
    if (platform && platform !== def.id) throw badRequest(`链接属于 ${def.label}，与所选平台不一致`, 'tracked.platform_mismatch', { platform: def.label });
    let path: string;
    try { path = decodeURIComponent(url.pathname); } catch { throw badRequest('链接格式不正确', 'tracked.bad_profile_url'); }
    const id = def.fromPath(path);
    if (!id) throw badRequest(`不是 ${def.label} 账号主页链接`, 'tracked.bad_profile_url_for', { platform: def.label });
    return { platform: def.id, ...id, profileUrl: def.profileUrl(id) };
  }
  if (!platform) throw badRequest('仅输入账号时需要选择平台', 'tracked.platform_required');
  const def = platformDef(platform);
  const id = def.fromHandle(raw.replace(/^@/, ''));
  if (!id) throw badRequest(`${def.label} 账号格式不正确`, 'tracked.bad_handle', { platform: def.label });
  return { platform: def.id, ...id, profileUrl: def.profileUrl(id) };
}

/** Enabled platforms with what each can do (sources are configured globally by admins). */
export async function platformInfo() {
  return Promise.all(PLATFORMS.filter((p) => isPlatformEnabled(p.id)).map(async (p) => ({
    id: p.id, label: p.label, metrics: p.metrics,
    api: p.source ? { ...p.source.capabilities, kind: p.source.kind, configured: await p.source.isConfigured() } : null,
  })));
}
